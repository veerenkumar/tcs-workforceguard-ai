"""
Generates a realistic, richly featured synthetic HR Attrition benchmark dataset
contextualized for a global IT services enterprise (TCS case study).

DISCLAIMER:
All records generated by this script are entirely synthetic and simulated for
academic, testing, and algorithmic demonstration purposes. No real TCS employee
or proprietary customer data is contained herein.
"""

import os
import random
import numpy as np
import pandas as pd
from datetime import datetime, timedelta

def generate_tcs_workforce_data(num_records=1470, seed=42):
    random.seed(seed)
    np.random.seed(seed)

    business_units = [
        "Banking, Financial Services & Insurance (BFSI)",
        "Retail, CPG & Travel",
        "Life Sciences & Healthcare",
        "Communications, Media & Info Services",
        "Manufacturing & Energy",
        "Digital & Cognitive Business Ops"
    ]
    
    departments = [
        "Technology & Engineering",
        "Enterprise Cloud & Agile",
        "Data & AI Services",
        "Quality Engineering & Testing",
        "Consulting & Digital Strategy"
    ]

    roles_by_dept = {
        "Technology & Engineering": [
            ("Associate Software Engineer", 1, 35000, 50000),
            ("Software Engineer", 2, 50000, 85000),
            ("Senior Software Engineer", 3, 85000, 140000),
            ("Technical Lead", 4, 140000, 220000),
            ("Engineering Manager", 5, 220000, 380000),
        ],
        "Enterprise Cloud & Agile": [
            ("Cloud Operations Engineer", 2, 55000, 90000),
            ("DevOps Specialist", 3, 90000, 150000),
            ("Cloud Architect", 4, 160000, 260000),
            ("Agile Delivery Lead", 4, 150000, 240000),
        ],
        "Data & AI Services": [
            ("Junior Data Analyst", 1, 40000, 60000),
            ("Data Engineer", 2, 60000, 100000),
            ("Senior Data Scientist", 3, 110000, 180000),
            ("AI Solutions Architect", 4, 180000, 300000),
            ("Practice Head - AI", 5, 280000, 450000),
        ],
        "Quality Engineering & Testing": [
            ("QA Automation Associate", 1, 32000, 48000),
            ("SDET II", 2, 48000, 80000),
            ("Lead QA Architect", 3, 80000, 130000),
            ("Test Program Manager", 4, 130000, 200000),
        ],
        "Consulting & Digital Strategy": [
            ("Associate Consultant", 2, 65000, 110000),
            ("Senior Consultant", 3, 110000, 180000),
            ("Principal Consultant", 4, 180000, 320000),
            ("Engagement Director", 5, 300000, 500000),
        ]
    }

    education_fields = [
        "Computer Science", "Information Technology", "Electronics & Comm",
        "Data Science & Analytics", "Business Administration", "Mechanical / Civil"
    ]

    remote_policies = ["On-site 5 days", "Hybrid (2-3 days)", "Remote-first"]
    travel_frequencies = ["Non-Travel", "Travel_Rarely", "Travel_Frequently"]
    exit_reasons = [
        "Compensation & Market Salary Parity",
        "Work-Life Balance & Overtime Burnout",
        "Lack of Clear Career Progression",
        "Desire for Modern Tech Stack Exposure",
        "Manager Relationship & Project Culture",
        "Higher Education / Global Relocation"
    ]

    records = []
    base_date = datetime(2026, 10, 1)

    for i in range(1, num_records + 1):
        emp_id = f"TCS-{10000 + i}"
        bu = random.choice(business_units)
        dept = random.choice(departments)
        role_info = random.choice(roles_by_dept[dept])
        role_name, job_level, min_inc, max_inc = role_info

        # Age and experience calculation
        total_working_years = max(1, int(np.random.gamma(shape=3.5, scale=2.5)))
        age = min(62, max(21, 21 + total_working_years + random.randint(0, 3)))
        years_at_company = min(total_working_years, max(0, int(np.random.beta(a=2, b=3) * total_working_years)))
        years_in_current_role = min(years_at_company, max(0, int(years_at_company * random.uniform(0.3, 0.9))))
        years_since_promotion = min(years_at_company, max(0, int(years_at_company * random.uniform(0.1, 0.8))))
        years_with_curr_manager = min(years_at_company, max(0, int(years_at_company * random.uniform(0.2, 0.85))))

        num_companies_worked = random.randint(0, min(8, max(1, total_working_years // 2)))

        monthly_income = int(np.random.uniform(min_inc, max_inc))
        if job_level == 1:
            salary_band = "Band 1 (Entry / YEP)"
        elif job_level == 2:
            salary_band = "Band 2 (Cadre C1/C2)"
        elif job_level == 3:
            salary_band = "Band 3 (Cadre C3/C3A)"
        elif job_level == 4:
            salary_band = "Band 4 (Lead C4/C5)"
        else:
            salary_band = "Band 5 (Executive CX)"

        overtime = np.random.choice(["Yes", "No"], p=[0.28, 0.72])
        overtime_hours = random.randint(15, 55) if overtime == "Yes" else random.randint(0, 8)
        deadline_pressure = random.choices([1, 2, 3, 4, 5], weights=[0.1, 0.2, 0.35, 0.25, 0.1])[0]
        
        # Satisfaction factors (1-4 scale)
        job_satisfaction = random.choices([1, 2, 3, 4], weights=[0.15, 0.25, 0.35, 0.25])[0]
        env_satisfaction = random.choices([1, 2, 3, 4], weights=[0.12, 0.23, 0.40, 0.25])[0]
        work_life_balance = random.choices([1, 2, 3, 4], weights=[0.18, 0.27, 0.35, 0.20])[0]
        relationship_satisfaction = random.choices([1, 2, 3, 4], weights=[0.10, 0.25, 0.40, 0.25])[0]
        job_involvement = random.choices([1, 2, 3, 4], weights=[0.08, 0.25, 0.45, 0.22])[0]
        performance_rating = random.choices([3, 4], weights=[0.82, 0.18])[0]

        client_travel = random.choices(travel_frequencies, weights=[0.60, 0.25, 0.15])[0]
        remote_policy = random.choices(remote_policies, weights=[0.25, 0.60, 0.15])[0]
        training_times_last_year = random.randint(0, 6)
        stock_option_level = random.choices([0, 1, 2, 3], weights=[0.45, 0.35, 0.15, 0.05])[0]
        distance_from_office_km = random.randint(2, 48)

        # Sensitive demographic features (for Governance / Fair ML testing, excluded from primary models)
        gender = random.choices(["Male", "Female", "Non-Binary"], weights=[0.62, 0.36, 0.02])[0]
        marital_status = random.choices(["Single", "Married", "Divorced"], weights=[0.33, 0.52, 0.15])[0]
        education_level = random.choices([1, 2, 3, 4, 5], weights=[0.1, 0.3, 0.4, 0.15, 0.05])[0]
        education_field = random.choice(education_fields)

        # Realistic attrition probability modeling based on real-world IT services drivers
        logit = -2.2  # baseline attrition around 15-16%
        
        # Overtime & Burnout
        if overtime == "Yes":
            logit += 1.15
        if work_life_balance == 1:
            logit += 0.95
        elif work_life_balance == 2:
            logit += 0.40
        elif work_life_balance == 4:
            logit -= 0.60

        # Job Satisfaction & Environment
        if job_satisfaction == 1:
            logit += 0.85
        elif job_satisfaction == 4:
            logit -= 0.70

        if env_satisfaction == 1:
            logit += 0.50

        # Career Stagnation
        if years_since_promotion >= 4:
            logit += 0.55
        if years_in_current_role >= 4 and years_since_promotion >= 3:
            logit += 0.45

        # Tenure effect (early career & 2-3 yr mark high risk)
        if years_at_company in [1, 2]:
            logit += 0.60
        elif years_at_company > 7:
            logit -= 0.75

        # Compensation & Stock Options
        if stock_option_level == 0:
            logit += 0.35
        elif stock_option_level >= 2:
            logit -= 0.50

        # Travel frequency
        if client_travel == "Travel_Frequently":
            logit += 0.45

        # Manager tenure buffer
        if years_with_curr_manager > 3 and relationship_satisfaction >= 3:
            logit -= 0.55

        # Convert logit to probability
        prob = 1.0 / (1.0 + np.exp(-logit))
        prob = np.clip(prob, 0.02, 0.92)

        is_attrited = np.random.rand() < prob
        attrition = "Yes" if is_attrited else "No"

        # Resignation date and exit reason if attrited
        if is_attrited:
            days_ago = random.randint(10, 720)
            resignation_date = (base_date - timedelta(days=days_ago)).strftime("%Y-%m-%d")
            
            # Weighted exit reason according to primary friction
            if overtime == "Yes" and work_life_balance <= 2:
                exit_reason = "Work-Life Balance & Overtime Burnout"
            elif years_since_promotion >= 3:
                exit_reason = "Lack of Clear Career Progression"
            elif monthly_income < (min_inc + max_inc) * 0.4:
                exit_reason = "Compensation & Market Salary Parity"
            else:
                exit_reason = random.choice(exit_reasons)
        else:
            resignation_date = None
            exit_reason = None

        record = {
            "EmployeeId": emp_id,
            "BusinessUnit": bu,
            "Department": dept,
            "JobRole": role_name,
            "JobLevel": job_level,
            "SalaryBand": salary_band,
            "MonthlyIncome": monthly_income,
            "Age": age,
            "Gender": gender,
            "MaritalStatus": marital_status,
            "Education": education_level,
            "EducationField": education_field,
            "TotalWorkingYears": total_working_years,
            "YearsAtCompany": years_at_company,
            "YearsInCurrentRole": years_in_current_role,
            "YearsSinceLastPromotion": years_since_promotion,
            "YearsWithCurrManager": years_with_curr_manager,
            "NumCompaniesWorked": num_companies_worked,
            "OverTime": overtime,
            "OvertimeHoursPerMonth": overtime_hours,
            "ProjectDeadlinesPressure": deadline_pressure,
            "ClientTravelFrequency": client_travel,
            "RemoteWorkPolicy": remote_policy,
            "CommuteDistanceKm": distance_from_office_km,
            "JobSatisfaction": job_satisfaction,
            "EnvironmentSatisfaction": env_satisfaction,
            "WorkLifeBalance": work_life_balance,
            "RelationshipSatisfaction": relationship_satisfaction,
            "JobInvolvement": job_involvement,
            "PerformanceRating": performance_rating,
            "TrainingTimesLastYear": training_times_last_year,
            "StockOptionLevel": stock_option_level,
            "Attrition": attrition,
            "ResignationDate": resignation_date,
            "ExitReason": exit_reason
        }
        records.append(record)

    df = pd.DataFrame(records)
    return df

if __name__ == "__main__":
    out_dir = os.path.dirname(os.path.abspath(__file__))
    os.makedirs(out_dir, exist_ok=True)
    df = generate_tcs_workforce_data(1470)
    out_path = os.path.join(out_dir, "tcs_workforce_benchmark.csv")
    df.to_csv(out_path, index=False)
    print(f"Generated {len(df)} records at {out_path}")
    print(f"Attrition count: {df['Attrition'].value_counts().to_dict()}")
    print(f"Attrition rate: {df['Attrition'].value_counts(normalize=True).get('Yes', 0):.2%}")
